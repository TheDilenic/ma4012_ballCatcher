int clampMotor(int value)
{
	if (value > 127)
		return 127;
	if (value < -127)
		return -127;
	return value;
}

void stopDrive()
{
	motor[leftMotor] = 0;
	motor[rightMotor] = 0;
}

void stopAllMotors()
{
	stopDrive();
	motor[catchSpinner] = 0;
	motor[releaseSpinner] = 0;
}

void waitForEmergencyRelease()
{
	if (SensorValue[emergencyStop] == 1)
	{
		stopAllMotors();
		while (SensorValue[emergencyStop] == 1)
			wait1Msec(20);
	}
}

int lineSensorActive(int sensorValue)
{
#if BOUNDARY_ACTIVE_LOW
	return sensorValue <= BOUNDARY_LINE_THRESHOLD;
#else
	return sensorValue >= BOUNDARY_LINE_THRESHOLD;
#endif
}

int boundaryMask()
{
	int mask = 0;

	if (lineSensorActive(SensorValue[frontTrackLeft]))
		mask |= 1;
	if (lineSensorActive(SensorValue[frontTrackRight]))
		mask |= 2;
	if (lineSensorActive(SensorValue[backTrackLeft]))
		mask |= 4;
	if (lineSensorActive(SensorValue[backTrackRight]))
		mask |= 8;
	if (SensorValue[backLimitLeft] == 1)
		mask |= 4;
	if (SensorValue[backLimitRight] == 1)
		mask |= 8;
	return mask;
}

int rearBoundaryDetected()
{
	return (boundaryMask() & 12) != 0;
}

int ballDetected()
{
	return SensorValue[detectBallLeft] >= BALL_DETECT_THRESHOLD
		|| SensorValue[detectBallRight] >= BALL_DETECT_THRESHOLD;
}

int storageOccupied()
{
	return SensorValue[storageCheck] >= STORAGE_OCCUPIED_THRESHOLD;
}

// Each digital compass input is active-low; multiple active inputs indicate
// an overlapping, diagonal direction.
int compassDirectionActive(int direction)
{
	switch (direction)
	{
	case COMPASS_NORTH:
		return SensorValue[North] == 0;
	case COMPASS_EAST:
		return SensorValue[East] == 0;
	case COMPASS_SOUTH:
		return SensorValue[South] == 0;
	case COMPASS_WEST:
		return SensorValue[West] == 0;
	}
	return 0;
}

int currentCompassDirection()
{
	if (compassDirectionActive(COMPASS_NORTH))
		return COMPASS_NORTH;
	if (compassDirectionActive(COMPASS_EAST))
		return COMPASS_EAST;
	if (compassDirectionActive(COMPASS_SOUTH))
		return COMPASS_SOUTH;
	if (compassDirectionActive(COMPASS_WEST))
		return COMPASS_WEST;
	return -1;
}

// Turn until the requested general direction is signalled or the turn times out.
int turnToCompassDirection(int direction, int clockwise)
{
	time1[T1] = 0;

	while (time1[T1] < TURN_TIMEOUT_MS)
	{
		waitForEmergencyRelease();
		if (compassDirectionActive(direction))
		{
			stopDrive();
			return 1;
		}

		if (clockwise)
		{
			motor[leftMotor] = TURN_POWER;
			motor[rightMotor] = -TURN_POWER;
		}
		else
		{
			motor[leftMotor] = -TURN_POWER;
			motor[rightMotor] = TURN_POWER;
		}
		wait1Msec(20);
	}

	stopDrive();
	return 0;
}

int turnOneCardinal(int clockwise)
{
	int currentDirection = currentCompassDirection();
	int targetDirection;

	if (currentDirection < 0)
		return 0;

	if (clockwise)
		targetDirection = (currentDirection + 1) % 4;
	else
		targetDirection = (currentDirection + 3) % 4;
	return turnToCompassDirection(targetDirection, clockwise);
}

// Timed movement is bounded and stops if the corresponding end sees a boundary.
void timedDrive(int leftPower, int rightPower, int durationMs)
{
	int elapsedMs = 0;
	int movingForward = leftPower > 0 || rightPower > 0;
	int movingBackward = leftPower < 0 || rightPower < 0;

	while (elapsedMs < durationMs)
	{
		waitForEmergencyRelease();
		if (movingForward && (boundaryMask() & 3) != 0)
			break;
		if (movingBackward && rearBoundaryDetected())
			break;

		motor[leftMotor] = leftPower;
		motor[rightMotor] = rightPower;
		wait1Msec(20);
		elapsedMs += 20;
	}
	stopDrive();
}

void avoidBoundary(int mask)
{
	int frontDetected = (mask & 3) != 0;
	int rearDetected = (mask & 12) != 0;
	int leftDetected = (mask & 5) != 0;
	int rightDetected = (mask & 10) != 0;

	if (frontDetected && !rearDetected)
		timedDrive(-BACKUP_POWER, -BACKUP_POWER, BOUNDARY_BACKUP_MS);
	else if (rearDetected && !frontDetected)
		timedDrive(BACKUP_POWER, BACKUP_POWER, BOUNDARY_BACKUP_MS);

	turnOneCardinal(leftDetected && !rightDetected);
}

void avoidOpponent()
{
	timedDrive(-BACKUP_POWER, -BACKUP_POWER, OBSTACLE_BACKUP_MS);
	turnOneCardinal(1);
}

int driveForwardForTime(int durationMs)
{
	int elapsedMs = 0;

	while (elapsedMs < durationMs)
	{
		int boundary;

		waitForEmergencyRelease();
		boundary = boundaryMask();
		if (boundary != 0)
		{
			stopDrive();
			avoidBoundary(boundary);
			return 0;
		}
		if (SensorValue[opponentCheck] >= OPPONENT_DETECT_THRESHOLD)
		{
			stopDrive();
			avoidOpponent();
			return 0;
		}

		motor[leftMotor] = DRIVE_POWER;
		motor[rightMotor] = DRIVE_POWER;
		wait1Msec(20);
		elapsedMs += 20;
	}

	stopDrive();
	return 1;
}

int approachAndCollect()
{
	int attempt;

	for (attempt = 0; attempt < BALL_PICKUP_ATTEMPTS; attempt++)
	{
		int elapsedMs = 0;
		int boundary = 0;
		int obstacle = 0;

		if (storageOccupied())
			return 1;

		motor[catchSpinner] = INTAKE_POWER;
		while (elapsedMs < BALL_APPROACH_TIMEOUT_MS
			&& !boundary && !obstacle)
		{
			int leftReading;
			int rightReading;
			int steering = 0;

			waitForEmergencyRelease();
			boundary = boundaryMask();
			if (boundary != 0)
				break;
			if (SensorValue[opponentCheck] >= OPPONENT_DETECT_THRESHOLD)
			{
				obstacle = 1;
				break;
			}
			if (storageOccupied())
				break;

			leftReading = SensorValue[detectBallLeft];
			rightReading = SensorValue[detectBallRight];
			if (leftReading >= BALL_DETECT_THRESHOLD
				&& rightReading < BALL_DETECT_THRESHOLD)
				steering = 12;
			else if (rightReading >= BALL_DETECT_THRESHOLD
				&& leftReading < BALL_DETECT_THRESHOLD)
				steering = -12;
			else if (leftReading >= BALL_DETECT_THRESHOLD
				&& rightReading >= BALL_DETECT_THRESHOLD)
			{
				steering = (leftReading - rightReading) / 50;
				if (steering > 12)
					steering = 12;
				else if (steering < -12)
					steering = -12;
			}

			motor[leftMotor] = clampMotor(APPROACH_POWER - steering);
			motor[rightMotor] = clampMotor(APPROACH_POWER + steering);
			wait1Msec(20);
			elapsedMs += 20;
		}

		stopDrive();
		motor[catchSpinner] = 0;
		if (storageOccupied())
			return 1;
		if (boundary != 0)
			avoidBoundary(boundary);
		else if (obstacle)
			avoidOpponent();
		else
			timedDrive(-APPROACH_POWER, -APPROACH_POWER, 300);
	}

	stopAllMotors();
	return 0;
}

int searchAndCollect()
{
	int sweep;

	for (sweep = 0; sweep < MAX_SEARCH_SWEEPS; sweep++)
	{
		int phase;

		for (phase = 0; phase < 4; phase++)
		{
			if (ballDetected() && approachAndCollect())
				return 1;
			if (!turnToCompassDirection(phase, 1))
				return 0;
		}

		if (ballDetected() && approachAndCollect())
			return 1;
		driveForwardForTime(SEARCH_ADVANCE_MS);
	}
	return 0;
}

// The robot faces away from the selected box side, then reverses until its
// rear line sensors detect the arena boundary.
int navigateToDepositBox()
{
	int targetFacingDirection;
	int elapsedMs = 0;

	if (BOX_ON_EAST_SIDE)
		targetFacingDirection = COMPASS_WEST;
	else
		targetFacingDirection = COMPASS_EAST;

	if (!turnToCompassDirection(targetFacingDirection, 1))
		return 0;

	while (elapsedMs < BOX_APPROACH_TIMEOUT_MS)
	{
		waitForEmergencyRelease();
		if ((lineSensorActive(SensorValue[backTrackLeft])
			|| lineSensorActive(SensorValue[backTrackRight])))
		{
			stopDrive();
			return 1;
		}
		if (SensorValue[opponentCheck] >= OPPONENT_DETECT_THRESHOLD)
		{
			stopDrive();
			avoidOpponent();
			return 0;
		}

		motor[leftMotor] = -APPROACH_POWER;
		motor[rightMotor] = -APPROACH_POWER;
		wait1Msec(20);
		elapsedMs += 20;
	}

	stopDrive();
	return 0;
}

int releaseBall()
{
	int attempt;

	for (attempt = 0; attempt < RELEASE_RETRIES; attempt++)
	{
		int elapsedMs;

		stopDrive();
		motor[releaseSpinner] = RELEASE_POWER;
		for (elapsedMs = 0; elapsedMs < RELEASE_DURATION_MS; elapsedMs += 20)
		{
			waitForEmergencyRelease();
			wait1Msec(20);
		}
		motor[releaseSpinner] = 0;
		wait1Msec(400);
		if (!storageOccupied())
			return 1;
	}
	return 0;
}

task main()
{
	stopAllMotors();

	while (SensorValue[buttonStart] == 0)
	{
		waitForEmergencyRelease();
		wait1Msec(20);
	}
	while (SensorValue[buttonStart] == 1)
		wait1Msec(20);

	while (depositedBallCount < MAX_BALLS)
	{
		if (!searchAndCollect())
			break;
		if (!navigateToDepositBox())
			break;
		if (!releaseBall())
			break;
		depositedBallCount++;
	}

	stopAllMotors();
	while (true)
	{
		waitForEmergencyRelease();
		wait1Msec(100);
	}
}

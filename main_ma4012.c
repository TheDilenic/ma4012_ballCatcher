// WORKFLOW: find ball -> move toward it -> check/avoid obstacles -> collect and
// check storage -> find/reach box -> release ball and check storage -> repeat.
// Each helper below handles one part of this cycle. Sensor thresholds and all
// measurements are starting values: calibrate them on the actual robot.

// MEASUREMENTS: distances are in cm; heading is degrees (0=east, 90=north).
// The robot pose is its center, and the box coordinates are its stopping point.
#define PI                              3.14159265
#define WHEEL_DIAMETER_CM               10.0
#define WHEEL_TRACK_CM                  28.0
// Encoder counts per full wheel revolution; polarity is +1 or -1 to correct signs.
#define ENCODER_TICKS_PER_WHEEL_REV     360.0
#define LEFT_ENCODER_POLARITY           1.0
#define RIGHT_ENCODER_POLARITY          1.0

#define ARENA_WIDTH_CM                  240.0
#define ARENA_HEIGHT_CM                 120.0
#define ROBOT_LENGTH_CM                 30.0
#define ROBOT_WIDTH_CM                  25.0
#define START_X_CM                      30.0
#define START_Y_CM                      30.0
#define START_HEADING_DEGREES           0.0
#define DEPOSIT_BOX_X_CM                210.0
#define DEPOSIT_BOX_Y_CM                90.0

// SENSOR CALIBRATION: compare each sensor's reading on the target and background.
// BOUNDARY_ACTIVE_LOW=1 means the line reads lower than the safe arena floor.
#define BALL_DETECT_THRESHOLD            1000
#define OPPONENT_DETECT_THRESHOLD        3000
#define STORAGE_OCCUPIED_THRESHOLD       1800
#define BOUNDARY_LINE_THRESHOLD          2000
#define BOUNDARY_ACTIVE_LOW              1

// LIMITS: these keep searching, pickup, and navigation from looping forever.
#define MAX_BALLS                        3
#define MAX_SEARCH_SWEEPS                80
#define SEARCH_SCAN_DEGREES              30.0
#define SEARCH_STEP_CM                   25.0
#define BALL_APPROACH_MAX_CM             70.0
#define BALL_APPROACH_TIMEOUT_MS         7000
#define BALL_PICKUP_ATTEMPTS             2
#define BOX_ARRIVAL_TOLERANCE_CM         12.0
#define MAX_BOX_NAVIGATION_ATTEMPTS      6

// MOTOR SETTINGS: powers use ROBOTC's -127..127 range; reverse signs if needed.
#define DRIVE_POWER                      75
#define APPROACH_POWER                   45
#define TURN_POWER                       55
#define INTAKE_POWER                     -127
#define RELEASE_POWER                    -100
#define STRAIGHT_CORRECTION_PER_CM       2.0
#define MAX_STEERING_CORRECTION          18
#define OBSTACLE_BACKUP_MS               350
#define OBSTACLE_TURN_DEGREES            40.0
#define BOUNDARY_BACKUP_MS               450
#define BOUNDARY_TURN_DEGREES            45.0
#define RELEASE_DURATION_MS              900
#define RELEASE_RETRIES                  2
#define DRIVE_TIMEOUT_MS                 8000
#define TURN_TIMEOUT_MS                  4000

float robotXcm = START_X_CM;
float robotYcm = START_Y_CM;
float robotHeadingDegrees = START_HEADING_DEGREES;
int depositedBallCount = 0;


// The compass signals general cardinal direction only; it does not track position.
// Set to 0 when the deposit box is along the west side instead of the east side.
#define BOX_ON_EAST_SIDE                 1

#define BALL_DETECT_THRESHOLD            1000
#define OPPONENT_DETECT_THRESHOLD        3000
#define STORAGE_OCCUPIED_THRESHOLD       1800
#define BOUNDARY_LINE_THRESHOLD           2000
#define BOUNDARY_ACTIVE_LOW               1


float absoluteFloat(float value)
{
	return value < 0.0 ? -value : value;
}

int clampMotor(int value)
{
	if (value > 127)
		return 127;
	if (value < -127)
		return -127;
	return value;
}

float wheelCircumferenceCm()
{
	return PI * WHEEL_DIAMETER_CM;
}

float encoderTicksToCm(int ticks, float polarity)
{
	return ticks * polarity * wheelCircumferenceCm() / ENCODER_TICKS_PER_WHEEL_REV;
}

void stopDrive()
{
	motor[leftMotor] = 0;
	motor[rightMotor] = 0;
}

void stopAllMotors()
{
	stopDrive();
	motor[catchSpinner] = 0;
	motor[releaseSpinner] = 0;
}

void waitForEmergencyRelease()
{
	if (SensorValue[emergencyStop] == 1)
	{
		stopAllMotors();
		while (SensorValue[emergencyStop] == 1)
			wait1Msec(20);
	}
}

int lineSensorActive(int sensorValue)
{
#if BOUNDARY_ACTIVE_LOW
	return sensorValue <= BOUNDARY_LINE_THRESHOLD;
#else
	return sensorValue >= BOUNDARY_LINE_THRESHOLD;
#endif
}

// Bits: front-left=1, front-right=2, rear-left=4, rear-right=8.
int boundaryMask()
{
	int mask = 0;

	if (lineSensorActive(SensorValue[frontTrackLeft]))
		mask |= 1;
	if (lineSensorActive(SensorValue[frontTrackRight]))
		mask |= 2;
	if (lineSensorActive(SensorValue[backTrackLeft]))
		mask |= 4;
	if (lineSensorActive(SensorValue[backTrackRight]))
		mask |= 8;
	if (SensorValue[backLimitLeft] == 1)
		mask |= 4;
	if (SensorValue[backLimitRight] == 1)
		mask |= 8;
	return mask;
}

int ballDetected()
{
	return SensorValue[detectBallLeft] >= BALL_DETECT_THRESHOLD
		|| SensorValue[detectBallRight] >= BALL_DETECT_THRESHOLD;
}

int storageOccupied()
{
	return SensorValue[storageCheck] >= STORAGE_OCCUPIED_THRESHOLD;
}

void resetDriveEncoders()
{
	SensorValue[encoderLeftInput] = 0;
	SensorValue[encoderRightInput] = 0;
}

void updatePoseFromEncoders()
{
	float leftDistanceCm = encoderTicksToCm(
		SensorValue[encoderLeftInput], LEFT_ENCODER_POLARITY);
	float rightDistanceCm = encoderTicksToCm(
		SensorValue[encoderRightInput], RIGHT_ENCODER_POLARITY);
	float turnRadians = (rightDistanceCm - leftDistanceCm) / WHEEL_TRACK_CM;
	float middleHeadingRadians =
		(robotHeadingDegrees * PI / 180.0) + (turnRadians / 2.0);
	float forwardDistanceCm = (leftDistanceCm + rightDistanceCm) / 2.0;

	robotXcm += forwardDistanceCm * cos(middleHeadingRadians);
	robotYcm += forwardDistanceCm * sin(middleHeadingRadians);
	robotHeadingDegrees += turnRadians * 180.0 / PI;
	while (robotHeadingDegrees >= 360.0)
		robotHeadingDegrees -= 360.0;
	while (robotHeadingDegrees < 0.0)
		robotHeadingDegrees += 360.0;
}

int poseFitsInsideArena(float xCm, float yCm, float headingDegrees)
{
	float headingRadians = headingDegrees * PI / 180.0;
	float halfLength = ROBOT_LENGTH_CM / 2.0;
	float halfWidth = ROBOT_WIDTH_CM / 2.0;
	float marginX = absoluteFloat(cos(headingRadians)) * halfLength
		+ absoluteFloat(sin(headingRadians)) * halfWidth;
	float marginY = absoluteFloat(sin(headingRadians)) * halfLength
		+ absoluteFloat(cos(headingRadians)) * halfWidth;

	return xCm >= marginX && xCm <= ARENA_WIDTH_CM - marginX
		&& yCm >= marginY && yCm <= ARENA_HEIGHT_CM - marginY;
}

void timedDrive(int leftPower, int rightPower, int durationMs)
{
	int elapsedMs = 0;

	resetDriveEncoders();
	while (elapsedMs < durationMs)
	{
		waitForEmergencyRelease();
		if ((leftPower < 0 || rightPower < 0)
			&& (SensorValue[backLimitLeft] == 1
				|| SensorValue[backLimitRight] == 1))
			break;
		motor[leftMotor] = leftPower;
		motor[rightMotor] = rightPower;
		wait1Msec(20);
		elapsedMs += 20;
	}
	stopDrive();
	updatePoseFromEncoders();
}

void avoidBoundary(int mask)
{
	int frontDetected = (mask & 3) != 0;
	int rearDetected = (mask & 12) != 0;
	int leftDetected = (mask & 5) != 0;
	int rightDetected = (mask & 10) != 0;
	float turnDegrees = BOUNDARY_TURN_DEGREES;

	// Move away from whichever end of the chassis crossed the line.
	if (frontDetected && !rearDetected)
		timedDrive(-DRIVE_POWER / 2, -DRIVE_POWER / 2, BOUNDARY_BACKUP_MS);
	else
		timedDrive(DRIVE_POWER / 2, DRIVE_POWER / 2, BOUNDARY_BACKUP_MS);

	if (leftDetected && !rightDetected)
		turnDegrees = -BOUNDARY_TURN_DEGREES;
	turnByDegrees(turnDegrees);
}

void avoidOpponent()
{
	timedDrive(-DRIVE_POWER / 2, -DRIVE_POWER / 2, OBSTACLE_BACKUP_MS);
	turnByDegrees(OBSTACLE_TURN_DEGREES);
}

int driveDistanceCm(float distanceCm)
{
	float direction;
	float targetCm;
	int completed = 0;
	int timedOut = 0;
	int boundary = 0;
	int obstacle = 0;
	int basePower;

	if (absoluteFloat(distanceCm) < 0.5)
		return 1;

	direction = distanceCm < 0.0 ? -1.0 : 1.0;
	targetCm = absoluteFloat(distanceCm);
	if (direction > 0.0
		&& !poseFitsInsideArena(
			robotXcm + distanceCm * cos(robotHeadingDegrees * PI / 180.0),
			robotYcm + distanceCm * sin(robotHeadingDegrees * PI / 180.0),
			robotHeadingDegrees))
	{
		turnByDegrees(180.0);
		return 0;
	}
	basePower = direction > 0.0 ? DRIVE_POWER : -DRIVE_POWER;
	resetDriveEncoders();
	time1[T1] = 0;

	while (!completed && !timedOut && !boundary && !obstacle)
	{
		float leftDistanceCm;
		float rightDistanceCm;
		float progressCm;
		float correction;
		int leftPower;
		int rightPower;

		waitForEmergencyRelease();

		boundary = boundaryMask();
		if ((direction > 0.0 && (boundary & 3) != 0)
			|| (direction < 0.0 && (boundary & 12) != 0))
			break;
		boundary = 0;
		if (direction > 0.0)
		{
			if (SensorValue[opponentCheck] >= OPPONENT_DETECT_THRESHOLD)
			{
				obstacle = 1;
				break;
			}
		}

		leftDistanceCm = encoderTicksToCm(
			SensorValue[encoderLeftInput], LEFT_ENCODER_POLARITY);
		rightDistanceCm = encoderTicksToCm(
			SensorValue[encoderRightInput], RIGHT_ENCODER_POLARITY);
		progressCm = direction * (leftDistanceCm + rightDistanceCm) / 2.0;
		if (progressCm >= targetCm)
		{
			completed = 1;
			break;
		}

		correction = (leftDistanceCm - rightDistanceCm) * direction
			* STRAIGHT_CORRECTION_PER_CM;
		if (correction > MAX_STEERING_CORRECTION)
			correction = MAX_STEERING_CORRECTION;
		else if (correction < -MAX_STEERING_CORRECTION)
			correction = -MAX_STEERING_CORRECTION;
		leftPower = clampMotor((int)(direction * (DRIVE_POWER - correction)));
		rightPower = clampMotor((int)(direction * (DRIVE_POWER + correction)));
		motor[leftMotor] = leftPower;
		motor[rightMotor] = rightPower;

		if (time1[T1] >= DRIVE_TIMEOUT_MS)
			timedOut = 1;
		wait1Msec(20);
	}

	stopDrive();
	updatePoseFromEncoders();
	if (boundary != 0)
	{
		avoidBoundary(boundary);
		return 0;
	}
	if (obstacle)
	{
		avoidOpponent();
		return 0;
	}
	return completed && !timedOut;
}

int turnByDegrees(float degrees)
{
	float direction;
	float targetWheelCm;
	int completed = 0;
	int timedOut = 0;

	if (absoluteFloat(degrees) < 0.5)
		return 1;

	direction = degrees < 0.0 ? -1.0 : 1.0;
	targetWheelCm = (WHEEL_TRACK_CM / 2.0)
		* absoluteFloat(degrees) * PI / 180.0;
	resetDriveEncoders();
	time1[T1] = 0;

	while (!completed && !timedOut)
	{
		float leftDistanceCm;
		float rightDistanceCm;
		float turnProgressCm;

		waitForEmergencyRelease();
		leftDistanceCm = encoderTicksToCm(
			SensorValue[encoderLeftInput], LEFT_ENCODER_POLARITY);
		rightDistanceCm = encoderTicksToCm(
			SensorValue[encoderRightInput], RIGHT_ENCODER_POLARITY);
		turnProgressCm = direction * (rightDistanceCm - leftDistanceCm) / 2.0;
		if (turnProgressCm >= targetWheelCm)
		{
			completed = 1;
			break;
		}

		motor[leftMotor] = (int)(-direction * TURN_POWER);
		motor[rightMotor] = (int)(direction * TURN_POWER);
		if (time1[T1] >= TURN_TIMEOUT_MS)
			timedOut = 1;
		wait1Msec(20);
	}

	stopDrive();
	updatePoseFromEncoders();
	return completed && !timedOut;
}

int turnToHeading(float headingDegrees)
{
	float difference = headingDegrees - robotHeadingDegrees;

	while (difference > 180.0)
		difference -= 360.0;
	while (difference < -180.0)
		difference += 360.0;
	return turnByDegrees(difference);
}

int approachAndCollect()
{
	int attempt;

	for (attempt = 0; attempt < BALL_PICKUP_ATTEMPTS; attempt++)
	{
		int elapsedMs = 0;
		float traveledCm = 0.0;
		int boundary = 0;
		int obstacle = 0;

		if (storageOccupied())
			return 1;

		motor[catchSpinner] = INTAKE_POWER;
		resetDriveEncoders();
		time1[T1] = 0;
		while (elapsedMs < BALL_APPROACH_TIMEOUT_MS
			&& traveledCm < BALL_APPROACH_MAX_CM
			&& !boundary && !obstacle)
		{
			int leftReading;
			int rightReading;
			int steering = 0;

			waitForEmergencyRelease();
			boundary = boundaryMask();
			if (boundary != 0)
				break;
			if (SensorValue[opponentCheck] >= OPPONENT_DETECT_THRESHOLD)
			{
				obstacle = 1;
				break;
			}
			if (storageOccupied())
				break;

			leftReading = SensorValue[detectBallLeft];
			rightReading = SensorValue[detectBallRight];
			if (leftReading >= BALL_DETECT_THRESHOLD
				&& rightReading < BALL_DETECT_THRESHOLD)
				steering = 12;
			else if (rightReading >= BALL_DETECT_THRESHOLD
				&& leftReading < BALL_DETECT_THRESHOLD)
				steering = -12;
			else if (leftReading >= BALL_DETECT_THRESHOLD
				&& rightReading >= BALL_DETECT_THRESHOLD)
			{
				steering = (leftReading - rightReading) / 50;
				if (steering > 12)
					steering = 12;
				else if (steering < -12)
					steering = -12;
			}

			motor[leftMotor] = clampMotor(APPROACH_POWER - steering);
			motor[rightMotor] = clampMotor(APPROACH_POWER + steering);
			wait1Msec(20);
			elapsedMs += 20;
			traveledCm = absoluteFloat(
				(encoderTicksToCm(SensorValue[encoderLeftInput], LEFT_ENCODER_POLARITY)
				+ encoderTicksToCm(SensorValue[encoderRightInput], RIGHT_ENCODER_POLARITY))
				/ 2.0);
			if (time1[T1] >= BALL_APPROACH_TIMEOUT_MS)
				break;
		}

		stopDrive();
		updatePoseFromEncoders();
		motor[catchSpinner] = 0;

		if (storageOccupied())
			return 1;
		if (boundary != 0)
			avoidBoundary(boundary);
		else if (obstacle)
			avoidOpponent();
		else
			traveledCm = absoluteFloat(
				(encoderTicksToCm(SensorValue[encoderLeftInput], LEFT_ENCODER_POLARITY)
				+ encoderTicksToCm(SensorValue[encoderRightInput], RIGHT_ENCODER_POLARITY))
				/ 2.0);

		if (!boundary && !obstacle)
		{
			if (traveledCm < 5.0)
				break;
			driveDistanceCm(-10.0);
		}
	}

	stopAllMotors();
	return 0;
}

int searchAndCollect()
{
	int sweep;

	for (sweep = 0; sweep < MAX_SEARCH_SWEEPS; sweep++)
	{
		int phase;

		for (phase = 0; phase < 3; phase++)
		{
			float turnDegrees = phase == 1
				? -2.0 * SEARCH_SCAN_DEGREES
				: SEARCH_SCAN_DEGREES;

			if (ballDetected() && approachAndCollect())
				return 1;
			if (!turnByDegrees(turnDegrees))
				return 0;
		}

		if (ballDetected() && approachAndCollect())
			return 1;
		driveDistanceCm(SEARCH_STEP_CM);
	}
	return 0;
}

int navigateToDepositBox()
{
	int attempt;

	if (!poseFitsInsideArena(
		DEPOSIT_BOX_X_CM, DEPOSIT_BOX_Y_CM, robotHeadingDegrees))
		return 0;

	for (attempt = 0; attempt < MAX_BOX_NAVIGATION_ATTEMPTS; attempt++)
	{
		float dx = DEPOSIT_BOX_X_CM - robotXcm;
		float dy = DEPOSIT_BOX_Y_CM - robotYcm;
		float distanceCm = sqrt(dx * dx + dy * dy);
		float headingDegrees;

		if (distanceCm <= BOX_ARRIVAL_TOLERANCE_CM)
			return 1;

		headingDegrees = atan2(dy, dx) * 180.0 / PI;
		if (!turnToHeading(headingDegrees))
			continue;
		if (driveDistanceCm(distanceCm))
			return 1;
	}
	return 0;
}

int releaseBall()
{
	int attempt;

	for (attempt = 0; attempt < RELEASE_RETRIES; attempt++)
	{
		int elapsedMs;

		stopDrive();
		motor[releaseSpinner] = RELEASE_POWER;
		for (elapsedMs = 0; elapsedMs < RELEASE_DURATION_MS; elapsedMs += 20)
		{
			waitForEmergencyRelease();
			wait1Msec(20);
		}
		motor[releaseSpinner] = 0;
		wait1Msec(400);
		if (!storageOccupied())
			return 1;
	}
	return 0;
}

task main()
{
	stopAllMotors();
	resetDriveEncoders();

	while (SensorValue[buttonStart] == 0)
	{
		waitForEmergencyRelease();
		wait1Msec(20);
	}
	while (SensorValue[buttonStart] == 1)
		wait1Msec(20);

	while (depositedBallCount < MAX_BALLS)
	{
		if (!searchAndCollect())
			break;
		if (!navigateToDepositBox())
			break;
		if (!releaseBall())
			break;
		depositedBallCount++;
	}

	stopAllMotors();
	while (true)
	{
		waitForEmergencyRelease();
		wait1Msec(100);
	}
}

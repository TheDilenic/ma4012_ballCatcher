// ==== Function Setup ==== //
void movement(const char* direction);
void rotation(const char* direction);
void searchBall();
void catchBall();
void checkBall();
void deliverBall();
void releaseBall();

// ==== Variable Setup ==== //
int cycle = 0;
float speedLeft = 0;
float speedRight = 0;
float speedControl = 1; //Controls power of the motors
int ballFound = 0;
int begin = 0;


task main(){
	while(1==1)
	{
	if(SensorValue(buttonStart) == 1)
   	{
     begin = 1;
  	}
	if (begin == 1)
		{
		movement("forward");
		delay(2250);
		movement("stop");
		while(cycle == 0)
			{
				if(SensorValue(backTrackLeft) <= 150 && SensorValue(backTrackRight) <= 150)
				{
					movement("forward");
					delay(500);
				}
				else if(SensorValue(backTrackRight) <= 150)
				{
					movement("forward");
					delay(500);
					rotation("clockwise");
					delay(400);
				}
				else if(SensorValue(frontTrackLeft) <= 150)
				{
					movement("back");
					delay(500);
					rotation("clockwise");
					delay(400);
				}
				else if(SensorValue(frontTrackRight) <= 150)
				{
					movement("back");
					delay(500);
					rotation("anticlockwise");
					delay(4000);
				}
				else if(SensorValue(backTrackLeft) <= 150)
				{
					movement("forward");
					delay(500);
					rotation("anticlockwise");
					delay(400);
				}
				else if(SensorValue(frontTrackLeft) <= 150 && SensorValue(frontTrackRight) <= 350)
				{
					movement("back");
					delay(500);
					rotation("clockwise");
					delay(1600);
				}
				else
				{
					searchBall();
					catchBall();
					deliverBall();
					releaseBall();
				}
			}
		}
	}
}

//Searches for the ball
void searchBall(){
	while (ballFound == 0){
	if (SensorValue(detectBallLeft) >= 1000){
		rotation("anticlockwise");
		delay(400);
		ballFound = 1;
	}
	else if (SensorValue(detectBallRight) >= 1000){
		rotation("clockwise");
		delay(400);
		ballFound = 1;
	}
	else if (SensorValue(detectBallLeft) >= 2000 && SensorValue(detectBallRight) >= 2000 || SensorValue(opponentCheck) >= 3000){
	 movement("back");
	 delay(200);
	 rotation("clockwise");
	 delay(500);
	}
	else
	{
		rotation("clockwise");
	}
}
}

//Catching Mechanism and Movement
void catchBall(){
		while(ballFound == 1){
		speedControl = 0.5;
		motor[catchSpinner] = -127;
		movement("forward");
		checkBall();
		}
}

//Check Ball
void checkBall(){
	if (SensorValue(storageCheck) >= 2000){
		motor[catchSpinner] = 0;
		motor[leftMotor] = 0;
		motor[rightMotor] = 0;
		speedControl = 1;
		ballFound = 2;
	}
}


//Deposit Box Alignment and Detection
void deliverBall(){
	if(SensorValue(North) == 0){
		movement("back");
		delay(2500);
	}
	else if(SensorValue(West) == 0){
		rotation("anticlockwise");
		delay(800);
		movement("back");
		delay(2500);
	}
	else if(SensorValue(East) == 0){
		rotation("clockwise");
		delay(800);
		movement("back");
		delay(2250);
	}
	else if(SensorValue(South) == 0){
		rotation("clockwise");
		delay(1600);
		movement("back");
		delay(2250);
	}
	else if(SensorValue(North) == 0 && SensorValue(East) == 0){
		rotation("clockwise");
		delay(400);
		movement("back");
		delay(2250);
	}
	else if(SensorValue(North) == 0 && SensorValue(West) == 0){
		rotation("anticlockwise");
		delay(400);
		movement("back");
		delay(2250);
	}
	else if(SensorValue(South) == 0 && SensorValue(East) == 0){
		rotation("clockwise");
		delay(400);
		movement("back");
		delay(2250);
	}
	else if(SensorValue(South) == 0 && SensorValue(West) == 0){
		rotation("anticlockwise");
		delay(400);
		movement("back");
		delay(2250);
	}
}

//Release Mechanism and Movement
void releaseBall(){
	if (SensorValue(backLimitLeft) == 1 && SensorValue(backLimitRight) == 1 && SensorValue(storageCheck) >= 2000){
		motor[rightMotor] = 0;
		motor[leftMotor] = 0;
		motor[releaseSpinner] = 60;
		delay(300);
		motor[releaseSpinner] = -60;
		delay(300);
		ballFound = 0;
		cycle = 1;

	}
}

//Movement controls
void movement(const char* direction){
	if (strcmp(direction, "forward") == 0){
		speedLeft = 127*speedControl;
		speedRight = 127*speedControl;
		}
	else if (strcmp(direction, "back") == 0){
		speedLeft = -127*speedControl;
		speedRight = -127*speedControl;
		}
	else if (strcmp(direction, "left") == 0){
		speedLeft = 60*speedControl;
		speedRight = 127*speedControl;
		}
	else if (strcmp(direction, "right") == 0){
		speedLeft = 127*speedControl;
		speedRight = 60*speedControl;
		}
	else {
		speedLeft = speedRight = 0;
	}

	motor[leftMotor] = speedLeft;
	motor[rightMotor] = speedRight;
}

//Rotation Controls
void rotation(const char* direction){
	speedControl = 0.5;
	if (strcmp(direction, "clockwise") == 0){
		speedLeft = 127*speedControl;
		speedRight = -127*speedControl;
		}
	else if (strcmp(direction, "anticlockwise") == 0){
		speedLeft = -127*speedControl;
		speedRight = 127*speedControl;
		}
	motor[leftMotor] = speedLeft;
	motor[rightMotor] = speedRight;
}

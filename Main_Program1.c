void checkBoundary();

// ==== Variable Setup ==== //
int cycle = 0;
float speedLeft = 0;
float speedRight = 0;
float speedControl = 1; //Controls power of the motors
int ballFound = 0;
int begin = 0;
int boundaryLevel = 250;

//Boundary Tracking
void checkBoundary(){
	if(SensorValue(backTrackLeft) <= boundaryLevel && SensorValue(backTrackRight) <= boundaryLevel)
	{
		movement("forward");
		delay(500);
	}
	else if(SensorValue(backTrackRight) <= boundaryLevel)
	{
		movement("forward");
		delay(500);
		rotation("clockwise");
		delay(400);
	}
	else if(SensorValue(frontTrackLeft) <= boundaryLevel	)
	{
		movement("back");
		delay(500);
		rotation("clockwise");
		delay(400);
	}
	else if(SensorValue(frontTrackRight) <= boundaryLevel)
	{
		movement("back");
		delay(500);
		rotation("anticlockwise");
		delay(4000);
	}
	else if(SensorValue(backTrackLeft) <= boundaryLevel)
	{
		movement("forward");
		delay(500);
		rotation("anticlockwise");
		delay(400);
	}
	else if(SensorValue(frontTrackLeft) <= boundaryLevel && SensorValue(frontTrackRight) <= boundaryLevel)
	{
		movement("back");
		delay(500);
		rotation("clockwise");
		delay(1600);
	}
}

//Movement controls
void movement(const char* direction){
	//checkBoundary();
	if (strcmp(direction, "forward") == 0){
		speedLeft = 127*speedControl;
		speedRight = 127*speedControl;
		}
	else if (strcmp(direction, "back") == 0){
		speedLeft = -127*speedControl;
		speedRight = -127*speedControl;
		}
	else if (strcmp(direction, "left") == 0){
		speedLeft = 60*speedControl;
		speedRight = 127*speedControl;
		}
	else if (strcmp(direction, "right") == 0){
		speedLeft = 127*speedControl;
		speedRight = 60*speedControl;
		}
	else {
		speedLeft = speedRight = 0;
	}

	motor[leftMotor] = speedLeft;
	motor[rightMotor] = speedRight;
}

//Rotation Controls
void rotation(const char* direction){
	speedControl = 0.5;
	//checkBoundary();
	if (strcmp(direction, "clockwise") == 0){
		speedLeft = 120*speedControl;
		speedRight = -120*speedControl;
		}
	else if (strcmp(direction, "anticlockwise") == 0){
		speedLeft = -120*speedControl;
		speedRight = 120*speedControl;
		}
	motor[leftMotor] = speedLeft;
	motor[rightMotor] = speedRight;
}

//Searches for the ball
void searchBall(){
	while (ballFound == 0){

	if (SensorValue(detectBallLeft) >= 1000){
		movement("stop");
		delay(1000);
		ballFound = 1;
	}
	else if (SensorValue(detectBallRight) >= 1000){
		movement("stop");
		delay(1000);
		ballFound = 1;
	}
	else if (SensorValue(detectBallLeft) >= 2000 && SensorValue(detectBallRight) >= 2000 || SensorValue(opponentCheck) >= 3000){
	 movement("back");
	 delay(200);
	 rotation("clockwise");
	 delay(500);
	}
	else
	{
		rotation("clockwise");
	}
}
}

//Catching Mechanism and Movement
void catchBall(){
		while(ballFound == 1){
		speedControl = 0.5;
		motor[catchSpinner] = -127;
		movement("forward");
		checkBall();
		}
}

//Check Ball
void checkBall(){
	if (SensorValue(storageCheck) >= 2000){
		motor[catchSpinner] = 0;
		motor[leftMotor] = 0;
		motor[rightMotor] = 0;
		speedControl = 1;
		ballFound = 2;
	}
}


//Deposit Box Alignment and Detection
void deliverBall(){
	// 0 means the robot is facing that direction, 1 means the robot is not facing that direction
	int checkSouth = SensorValue(North) == 1 && SensorValue(East) == 1 && SensorValue(West) == 1;

	while(checkSouth == 0){
		rotation("clockwise");
		if(checkSouth == 1){
			movement("back");
			delay(1000);
			movement("stop");
			break;
		}
	}
}

//Release Mechanism and Movement
void releaseBall(){
	if (SensorValue(backLimitLeft) == 1 && SensorValue(backLimitRight) == 1){
		motor[rightMotor] = 0;
		motor[leftMotor] = 0;
		motor[releaseSpinner] = 60;
		delay(300);
		motor[releaseSpinner] = -60;
		delay(300);
		ballFound = 0;
		cycle = 1;

	}
}

task main(){
	while(1==1)
	{
	if(SensorValue(buttonStart) == 1)
   	{
     begin = 1;
  	}
	if (begin == 1)
		{
		movement("forward");
		delay(2250);
		movement("stop");
		while(cycle == 0)
			{
			searchBall();
			catchBall();
			deliverBall();
			releaseBall();
			}
		}
	}
}

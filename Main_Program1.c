//Searches for the ball
void searchBall(){
	while (ballFound == 0){
	if (SensorValue(detectBallLeft) >= 1000){
		movement("stop");
		delay(1000);
		ballFound = 1;
	}
	else if (SensorValue(detectBallRight) >= 1000){
		movement("stop");
		delay(1000);
		ballFound = 1;
	}
	else if (SensorValue(detectBallLeft) >= 2000 && SensorValue(detectBallRight) >= 2000 || SensorValue(opponentCheck) >= 3000){
	 movement("back");
	 delay(200);
	 rotation("clockwise");
	 delay(500);
	}
	else
	{
		rotation("clockwise");
	}
}
}

//Check Ball
void checkBall(){
	if (SensorValue(storageCheck) >= 1800){
		motor[catchSpinner] = 0;
		motor[leftMotor] = 0;
		motor[rightMotor] = 0;
		ballFound = 0;
	}
}

//Catching Mechanism and Movement
void catchBall(){
		while(ballFound == 1){
		motor[catchSpinner] = -127;
		motor[leftMotor] = 60;
		motor[rightMotor] = 60;
		checkBall();
		}
}

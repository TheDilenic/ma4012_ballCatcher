//Check Ball
void checkBall(){
	if (SensorValue(storageCheck) >= 2000){
		motor[catchSpinner] = 0;
		motor[leftMotor] = 0;
		motor[rightMotor] = 0;
		speedControl = 1;
		ballFound = 2;
	}
	else
		{
			ballFound = 0;
	}

}



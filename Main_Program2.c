void searchBall(){
    while (ballFound == 0){
        int left  = SensorValue(detectBallLeft);
        int right = SensorValue(detectBallRight);
        if (left >= 1000){
            movement("stop",100);
            rotation("anticlockwise");
            delay(250);
            ballFound = 1;
        }
        else if (right >= 1000){
            movement("stop",100);
            rotation("clockwise");
            delay(100);
            ballFound = 1;
        }
        else {
            checkBall();
            if (i <= 1){
                scanAndMove(0);
            }
            else if (i <= 3) {
                scanAndMove(1);
            }
            else{
            		i = 0;
          	}
        }
    }
}

